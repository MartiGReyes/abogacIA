BEGIN;
DO $$ BEGIN
 IF current_database() <> 'contacto_operativo_test' OR current_user <> 'operativa_owner' THEN
 RAISE EXCEPTION 'Migracion exclusiva de la base aislada'; END IF;
END $$;
CREATE TABLE operativa.cuenta_prueba (
 id_abogado bigint PRIMARY KEY REFERENCES public.abogados_registrados(id_abogado),
 contexto uuid NOT NULL UNIQUE,
 dni_cifrado bytea CHECK (octet_length(dni_cifrado) BETWEEN 35 AND 36),
 telefono_cifrado bytea CHECK (octet_length(telefono_cifrado)=41)
);
GRANT SELECT,INSERT,UPDATE ON operativa.cuenta_prueba TO operativa_runtime;
GRANT INSERT,UPDATE ON public.abogados_registrados,public.abogado_especialidades TO operativa_runtime;
GRANT DELETE ON public.abogado_especialidades TO operativa_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO operativa_runtime;
CREATE TABLE solicitud_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_abogado bigint NOT NULL REFERENCES abogados_registrados(id_abogado),
  id_ciudadano bigint NOT NULL CHECK (id_ciudadano > 0), -- referencia lógica externa
  area_juridica varchar(100) NOT NULL CHECK (length(trim(area_juridica)) > 0),
  descripcion varchar(4000) NOT NULL,
  estado varchar(12) NOT NULL CHECK (estado IN ('PENDIENTE','ACEPTADA','RECHAZADA','CANCELADA')),
  creada_en timestamptz NOT NULL,
  aceptada_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'ACEPTADA') = (aceptada_en IS NOT NULL)),
  CHECK (aceptada_en IS NULL OR aceptada_en >= creada_en)
);
CREATE TABLE asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_solicitud bigint NOT NULL UNIQUE REFERENCES solicitud_asesoramiento(id),
  estado varchar(12) NOT NULL CHECK (estado IN ('EN_CURSO','FINALIZADO','CANCELADO')),
  iniciado_en timestamptz NOT NULL,
  finalizado_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'FINALIZADO') = (finalizado_en IS NOT NULL)),
  CHECK (finalizado_en IS NULL OR finalizado_en >= iniciado_en)
);
CREATE TABLE valoracion_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_asesoramiento bigint NOT NULL UNIQUE REFERENCES asesoramiento(id),
  puntuacion smallint NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
  creada_en timestamptz NOT NULL
);
CREATE TABLE pago_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_asesoramiento bigint NOT NULL REFERENCES asesoramiento(id),
  clave_operacion varchar(160) NOT NULL UNIQUE,
  importe numeric(19,2) NOT NULL CHECK (importe > 0),
  moneda char(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
  estado varchar(12) NOT NULL CHECK (estado IN ('PENDIENTE','COBRADO','CANCELADO','RECHAZADO')),
  registrado_en timestamptz NOT NULL,
  cobrado_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'COBRADO') = (cobrado_en IS NOT NULL)),
  CHECK (cobrado_en IS NULL OR cobrado_en >= registrado_en)
);
CREATE INDEX ix_solicitud_titular_aceptada ON solicitud_asesoramiento
  (id_abogado, aceptada_en, id) WHERE aceptada_en IS NOT NULL;
CREATE INDEX ix_solicitud_titular_creada ON solicitud_asesoramiento(id_abogado, creada_en, id);
CREATE INDEX ix_asesoramiento_inicio ON asesoramiento(iniciado_en, id);
CREATE INDEX ix_asesoramiento_fin ON asesoramiento(finalizado_en, id)
  WHERE estado = 'FINALIZADO';
CREATE INDEX ix_valoracion_fecha ON valoracion_asesoramiento(creada_en, id_asesoramiento);
CREATE INDEX ix_pago_asesoramiento_fecha ON pago_asesoramiento(id_asesoramiento, cobrado_en, id);
CREATE INDEX ix_pago_cobrado ON pago_asesoramiento(moneda, cobrado_en, id_asesoramiento)
  WHERE estado = 'COBRADO';

GRANT SELECT ON solicitud_asesoramiento,asesoramiento,valoracion_asesoramiento,pago_asesoramiento TO operativa_runtime;
CREATE ROLE ciudadanos_runtime LOGIN PASSWORD :'dev_citizen_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
GRANT CONNECT ON DATABASE contacto_operativo_test TO ciudadanos_runtime;
CREATE SCHEMA ciudadanos_cuenta AUTHORIZATION operativa_owner;
CREATE TABLE ciudadanos_cuenta.estado(id_estado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre_estado varchar(255) NOT NULL UNIQUE);
INSERT INTO ciudadanos_cuenta.estado(nombre_estado) VALUES('PENDIENTE'),('REGISTRADO'),('BAJA');
CREATE TABLE ciudadanos_cuenta.ciudadano(
 id_ciudadano bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(255) NOT NULL,apellido varchar(255) NOT NULL,dni varchar(8) NOT NULL UNIQUE,
 fecha_nacimiento date NOT NULL,direccion varchar(255),mail varchar(255) NOT NULL UNIQUE,
 nro_celular varchar(255),contrasena_hash varchar(255) NOT NULL,codigo_confirmacion varchar(255),
 id_estado bigint NOT NULL REFERENCES ciudadanos_cuenta.estado(id_estado),correo_confirmado boolean DEFAULT false NOT NULL,
 verificacion_dni varchar(255),sesion_didit varchar(255),resultado_didit_id varchar(255),acceso_registro_hash varchar(255) UNIQUE,acceso_registro_vence timestamptz
);
CREATE TABLE ciudadanos_cuenta.verificacion_identidad(
 id_ciudadano bigint PRIMARY KEY,version bigint,sesion varchar(255) UNIQUE,referencia varchar(255),workflow varchar(255),workflow_version integer,
 url varchar(2048),estado varchar(255),aviso_version varchar(255),aviso_hash varchar(255),consentimiento_fecha timestamptz,consentimiento boolean NOT NULL,
 inicio timestamptz,proxima_consulta timestamptz,lease_hasta timestamptz,operacion varchar(255),intentos integer NOT NULL,consultas integer NOT NULL,errores integer NOT NULL,ultima_consulta timestamptz,error_codigo varchar(255)
);
GRANT USAGE ON SCHEMA ciudadanos_cuenta TO ciudadanos_runtime;
GRANT SELECT,INSERT,UPDATE ON ALL TABLES IN SCHEMA ciudadanos_cuenta TO ciudadanos_runtime;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA ciudadanos_cuenta TO ciudadanos_runtime;
COMMIT;
