test('valoración real del ensayo mantiene estrellas rellenables y teclado',async({page,isMobile})=>{
 await login(page,'CIUDADANO');await page.goto('/mis-consultas')
 await page.getByRole('button',{name:'Ver detalle y valorar',exact:true}).last().click()
 const stars=page.locator('.stars-input'),labels=stars.locator('label'),radios=stars.getByRole('radio')
 await expect(radios).toHaveCount(5)
 if(isMobile)await labels.nth(3).tap();else await labels.nth(3).click()
 await expect(radios.nth(3)).toBeChecked();await expect(stars.locator('[data-filled="true"]')).toHaveCount(4)
 await radios.nth(3).focus();await page.keyboard.press('ArrowLeft');await expect(radios.nth(2)).toBeChecked()
 await page.getByRole('button',{name:'Guardar cambios de valoración',exact:true}).click()
 await expect(page.getByRole('dialog').getByText('Valoración guardada correctamente.',{exact:true})).toBeVisible()
})
