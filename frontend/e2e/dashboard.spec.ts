import { test, expect, type Page } from '@playwright/test'
async function login(page: Page, cuenta = 1) {
  await page.goto('/iniciar-sesion')
  await page.getByRole('radio', { name: 'Abogado', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`abogado${cuenta}.dashboard@example.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Dashboard-Prueba-2026!')
  await page.getByRole('main').getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page).toHaveURL('http://127.0.0.1:5181/')
  await expect(page.getByRole('heading', { name: 'Hola, Prueba' })).toBeVisible()
}
test('login abre directamente Home profesional y persiste al recargar /', async ({ page }) => {
  await login(page)
  await expect(page.getByRole('heading', { name: 'Solicitudes aceptadas' })).toBeVisible()
  await expect(page.getByText('Sin cobros registrados', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Hola, Prueba' })).toBeVisible()
  await page.getByRole('link', { name: 'Ver asesoramiento #1', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Asesoramiento #1', exact: true })).toBeVisible()
  await expect(page.getByText('Caso sintético finalizado')).toBeVisible()
  await page.getByRole('link', { name: 'Volver a mi Home' }).click()
  await expect(page.getByRole('heading', { name: 'Hola, Prueba' })).toBeVisible()
})
test('abogado sin actividad ve vacíos, nunca promedios inventados', async ({ page }) => {
  await login(page, 3)
  await expect(page.getByText('Sin valoraciones todavía', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('No hay registros para estos filtros.', { exact: true })).toBeVisible()
  await expect(page.getByText('Sin cobros registrados', { exact: true })).toBeVisible()
})
test('errores y carga se muestran y permiten reintentar', async ({ page }) => {
  await page.route('**/dashboard/resumen?**', async route => {
    await new Promise(resolve => setTimeout(resolve, 700))
    await route.fulfill({ status: 503, body: '{}' })
  })
  await login(page)
  await expect(page.getByText('Cargando datos…').first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reintentar' }).first()).toBeVisible()
  await page.unroute('**/dashboard/resumen?**')
  await page.getByRole('button', { name: 'Reintentar' }).first().click()
  await expect(page.getByRole('heading', { name: 'Solicitudes aceptadas' })).toBeVisible()
})
for (const ancho of [360, 768, 1440]) test(`responsive a ${ancho}px sin desbordamiento de página`, async ({ page }) => {
  await page.setViewportSize({ width: ancho, height: 900 })
  await login(page)
  await expect(page.getByRole('heading', { name: 'Detalle de tu actividad' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Ver asesoramiento #1', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `test-results/dashboard-${ancho}.png`, fullPage: true })
})
test('protege ruta directa y Home público conserva su contenido', async ({ page }) => {
  await page.goto('/dashboard-abogado/asesoramientos/1')
  await expect(page).toHaveURL(/iniciar-sesion/)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Hola, Prueba' })).toHaveCount(0)
})
test('filtros de finalizados e ingresos llevan al detalle correcto', async ({ page }) => {
  await login(page)
  await page.getByRole('combobox', { name: 'Estado', exact: true }).selectOption('FINALIZADO')
  await page.getByRole('combobox', { name: 'Fecha del filtro', exact: true }).selectOption('finalizacion')
  await expect(page.getByText('1 resultados', { exact: false })).toBeVisible()
  await page.getByRole('combobox', { name: 'Listado', exact: true }).selectOption('ingresos/por-asesoramiento')
  await page.getByRole('combobox', { name: 'Ordenar por', exact: true }).selectOption('importe')
  await expect(page.getByRole('link', { name: 'Ver asesoramiento #1', exact: true })).toBeVisible()
})
for (const rol of ['CIUDADANO', 'ADMIN']) test(`mantiene navegación existente de ${rol}`, async ({ page }) => {
  // Fixture solo de UI: no se envía este token a una API real.
  const token = `ui.${Buffer.from(JSON.stringify({ exp: Math.floor(Date.now() / 1000) + 300 })).toString('base64url')}.fixture`
  await page.route('**/api/auth/login', route => route.fulfill({ json: { token, rol, idUsuario: '9000' } }))
  await page.route('**/api/ciudadanos/me', route => route.fulfill({ json: { nombre: 'Ciudadano', apellido: 'Prueba', mail: 'ciudadano@example.com' } }))
  await page.goto(rol === 'ADMIN' ? '/admin/iniciar-sesion' : '/iniciar-sesion')
  await page.getByLabel('Email', { exact: true }).fill('ui@example.com')
  await page.getByLabel('Contraseña', { exact: true }).fill('synthetic-password')
  await page.getByRole('main').getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page).toHaveURL(rol === 'ADMIN' ? /\/admin$/ : 'http://127.0.0.1:5181/')
  if (rol === 'ADMIN') await expect(page.getByRole('heading', { name: 'Administración', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Solicitudes aceptadas', exact: true })).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Solicitudes aceptadas', exact: true })).toHaveCount(0)
})
