-- Baseline for the existing JPA entities. No real data is imported.
CREATE ROLE dashboard_reader LOGIN PASSWORD :'dev_app_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
REVOKE ALL ON DATABASE dashboard_abogados_test FROM PUBLIC;
GRANT CONNECT ON DATABASE dashboard_abogados_test TO dashboard_reader;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE TABLE public.estado (
    id_estado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estado varchar(255)
);
CREATE TABLE public.padron (
    nro_matricula varchar(255) PRIMARY KEY,
    estado varchar(16)
);
CREATE TABLE public.abogados_registrados (
    id_abogado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint DEFAULT 0 NOT NULL,
    acceso_registro_hash varchar(255) UNIQUE,
    acceso_registro_vence timestamp(6) with time zone,
    padron_matricula varchar(255) REFERENCES public.padron(nro_matricula),
    nombre varchar(255), apellido varchar(255),
    dni varchar(8) NOT NULL UNIQUE, mail varchar(255) NOT NULL UNIQUE,
    nro_celular varchar(255), nro_matricula varchar(255), colegio_profesional varchar(255),
    provincia varchar(255), anios_experiencia integer, ubicacion varchar(255),
    descripcion_profesional varchar(2000), contrasena_hash varchar(255), codigo_confirmacion varchar(255),
    dni_verificado boolean, matricula_verificada boolean, fecha_registro date,
    id_estado bigint REFERENCES public.estado(id_estado),
    fecha_nacimiento date, genero varchar(255), domicilio varchar(255), honorarios numeric(38,2),
    direccion_profesional varchar(255), correo_confirmado boolean DEFAULT false,
    verificacion_dni varchar(255), validacion_matricula varchar(255),
    sesion_didit varchar(255), resultado_didit_id varchar(255),
    confirmacion_vence timestamp(6) with time zone, intentos_confirmacion integer DEFAULT 0 NOT NULL
);
CREATE TABLE public.abogado_especialidades (
    id_abogado bigint NOT NULL REFERENCES public.abogados_registrados(id_abogado),
    especialidad varchar(255), UNIQUE (id_abogado, especialidad)
);
CREATE TABLE public.padron_evidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula varchar(255), dni varchar(255), nombre_completo varchar(255),
    estado varchar(255), hoja varchar(255), fila integer NOT NULL, version_archivo varchar(255)
);
CREATE TABLE public.verificacion_identidad (
    id_abogado bigint PRIMARY KEY, version bigint, sesion varchar(255) UNIQUE,
    referencia varchar(255), workflow varchar(255), workflow_version integer,
    url varchar(2048), estado varchar(255), aviso_version varchar(255), aviso_hash varchar(255),
    consentimiento_fecha timestamp(6) with time zone, consentimiento boolean NOT NULL,
    inicio timestamp(6) with time zone, proxima_consulta timestamp(6) with time zone,
    lease_hasta timestamp(6) with time zone, operacion varchar(255),
    intentos integer NOT NULL, consultas integer NOT NULL, errores integer NOT NULL,
    ultima_consulta timestamp(6) with time zone, error_codigo varchar(255)
);
INSERT INTO public.estado(nombre_estado) VALUES ('PENDIENTE'), ('REGISTRADO'), ('BAJA');


CREATE TABLE solicitud_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_abogado bigint NOT NULL REFERENCES abogados_registrados(id_abogado),
  id_ciudadano bigint NOT NULL CHECK (id_ciudadano > 0), -- referencia lógica externa
  area_juridica varchar(100) NOT NULL CHECK (length(trim(area_juridica)) > 0),
  descripcion varchar(4000) NOT NULL,
  estado varchar(12) NOT NULL CHECK (estado IN ('PENDIENTE','ACEPTADA','RECHAZADA','CANCELADA')),
  creada_en timestamptz NOT NULL,
  aceptada_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'ACEPTADA') = (aceptada_en IS NOT NULL)),
  CHECK (aceptada_en IS NULL OR aceptada_en >= creada_en)
);
CREATE TABLE asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_solicitud bigint NOT NULL UNIQUE REFERENCES solicitud_asesoramiento(id),
  estado varchar(12) NOT NULL CHECK (estado IN ('EN_CURSO','FINALIZADO','CANCELADO')),
  iniciado_en timestamptz NOT NULL,
  finalizado_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'FINALIZADO') = (finalizado_en IS NOT NULL)),
  CHECK (finalizado_en IS NULL OR finalizado_en >= iniciado_en)
);
CREATE TABLE valoracion_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_asesoramiento bigint NOT NULL UNIQUE REFERENCES asesoramiento(id),
  puntuacion smallint NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
  creada_en timestamptz NOT NULL
);
CREATE TABLE pago_asesoramiento (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_asesoramiento bigint NOT NULL REFERENCES asesoramiento(id),
  clave_operacion varchar(160) NOT NULL UNIQUE,
  importe numeric(19,2) NOT NULL CHECK (importe > 0),
  moneda char(3) NOT NULL CHECK (moneda ~ '^[A-Z]{3}$'),
  estado varchar(12) NOT NULL CHECK (estado IN ('PENDIENTE','COBRADO','CANCELADO','RECHAZADO')),
  registrado_en timestamptz NOT NULL,
  cobrado_en timestamptz,
  version bigint NOT NULL DEFAULT 0,
  CHECK ((estado = 'COBRADO') = (cobrado_en IS NOT NULL)),
  CHECK (cobrado_en IS NULL OR cobrado_en >= registrado_en)
);
CREATE INDEX ix_solicitud_titular_aceptada ON solicitud_asesoramiento
  (id_abogado, aceptada_en, id) WHERE aceptada_en IS NOT NULL;
CREATE INDEX ix_solicitud_titular_creada ON solicitud_asesoramiento(id_abogado, creada_en, id);
CREATE INDEX ix_asesoramiento_inicio ON asesoramiento(iniciado_en, id);
CREATE INDEX ix_asesoramiento_fin ON asesoramiento(finalizado_en, id)
  WHERE estado = 'FINALIZADO';
CREATE INDEX ix_valoracion_fecha ON valoracion_asesoramiento(creada_en, id_asesoramiento);
CREATE INDEX ix_pago_asesoramiento_fecha ON pago_asesoramiento(id_asesoramiento, cobrado_en, id);
CREATE INDEX ix_pago_cobrado ON pago_asesoramiento(moneda, cobrado_en, id_asesoramiento)
  WHERE estado = 'COBRADO';

GRANT USAGE ON SCHEMA public TO dashboard_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO dashboard_reader;
COMMIT;
