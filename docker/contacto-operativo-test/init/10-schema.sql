\set ON_ERROR_STOP on
\getenv dev_app_password OP_DB_PASSWORD

BEGIN;
DO $$ BEGIN
    IF current_database() <> 'contacto_operativo_test' OR current_user <> 'operativa_owner' THEN
        RAISE EXCEPTION 'Inicialización permitida solo en la base y propietario de desarrollo';
    END IF;
END $$;

-- Baseline for the existing JPA entities. No real data is imported.
CREATE ROLE operativa_runtime LOGIN PASSWORD :'dev_app_password'
    NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
REVOKE ALL ON DATABASE contacto_operativo_test FROM PUBLIC;
GRANT CONNECT ON DATABASE contacto_operativo_test TO operativa_runtime;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE TABLE public.estado (
    id_estado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_estado varchar(255)
);
CREATE TABLE public.padron (
    nro_matricula varchar(255) PRIMARY KEY,
    estado varchar(16)
);
CREATE TABLE public.abogados_registrados (
    id_abogado bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version bigint DEFAULT 0 NOT NULL,
    acceso_registro_hash varchar(255) UNIQUE,
    acceso_registro_vence timestamp(6) with time zone,
    padron_matricula varchar(255) REFERENCES public.padron(nro_matricula),
    nombre varchar(255), apellido varchar(255),
    dni varchar(8) NOT NULL UNIQUE, mail varchar(255) NOT NULL UNIQUE,
    nro_celular varchar(255), nro_matricula varchar(255), colegio_profesional varchar(255),
    provincia varchar(255), anios_experiencia integer, ubicacion varchar(255),
    descripcion_profesional varchar(2000), contrasena_hash varchar(255), codigo_confirmacion varchar(255),
    dni_verificado boolean, matricula_verificada boolean, fecha_registro date,
    id_estado bigint REFERENCES public.estado(id_estado),
    fecha_nacimiento date, genero varchar(255), domicilio varchar(255), honorarios numeric(38,2),
    direccion_profesional varchar(255), correo_confirmado boolean DEFAULT false,
    verificacion_dni varchar(255), validacion_matricula varchar(255),
    sesion_didit varchar(255), resultado_didit_id varchar(255),
    confirmacion_vence timestamp(6) with time zone, intentos_confirmacion integer DEFAULT 0 NOT NULL
);
CREATE TABLE public.abogado_especialidades (
    id_abogado bigint NOT NULL REFERENCES public.abogados_registrados(id_abogado),
    especialidad varchar(255), UNIQUE (id_abogado, especialidad)
);
CREATE TABLE public.padron_evidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula varchar(255), dni varchar(255), nombre_completo varchar(255),
    estado varchar(255), hoja varchar(255), fila integer NOT NULL, version_archivo varchar(255)
);
CREATE TABLE public.verificacion_identidad (
    id_abogado bigint PRIMARY KEY, version bigint, sesion varchar(255) UNIQUE,
    referencia varchar(255), workflow varchar(255), workflow_version integer,
    url varchar(2048), estado varchar(255), aviso_version varchar(255), aviso_hash varchar(255),
    consentimiento_fecha timestamp(6) with time zone, consentimiento boolean NOT NULL,
    inicio timestamp(6) with time zone, proxima_consulta timestamp(6) with time zone,
    lease_hasta timestamp(6) with time zone, operacion varchar(255),
    intentos integer NOT NULL, consultas integer NOT NULL, errores integer NOT NULL,
    ultima_consulta timestamp(6) with time zone, error_codigo varchar(255)
);
INSERT INTO public.estado(nombre_estado) VALUES ('PENDIENTE'), ('REGISTRADO'), ('BAJA');


CREATE SCHEMA operativa;
CREATE TABLE operativa.campania (
    id uuid PRIMARY KEY,
    creada_en timestamptz NOT NULL,
    vence_en timestamptz NOT NULL CHECK (vence_en > creada_en),
    activa boolean NOT NULL
);
CREATE TABLE operativa.sesion (
    hash char(64) PRIMARY KEY,
    campania_id uuid NOT NULL REFERENCES operativa.campania(id),
    rol varchar(16) NOT NULL CHECK (rol IN ('OPERADOR','PARTICIPANTE')),
    vence_en timestamptz NOT NULL,
    revocada boolean NOT NULL DEFAULT false
);
CREATE TABLE operativa.invitacion (
    hash char(64) PRIMARY KEY,
    campania_id uuid NOT NULL REFERENCES operativa.campania(id),
    vence_en timestamptz NOT NULL,
    consumida boolean NOT NULL DEFAULT false
);
CREATE TABLE operativa.perfil (
    id uuid PRIMARY KEY,
    campania_id uuid NOT NULL UNIQUE REFERENCES operativa.campania(id),
    nombre_visible varchar(100) NOT NULL,
    dni_cifrado bytea NOT NULL CHECK (octet_length(dni_cifrado) >= 35),
    telefono_cifrado bytea NOT NULL CHECK (octet_length(telefono_cifrado) = 41),
    version_clave varchar(32) NOT NULL CHECK (version_clave = 'v1'),
    especialidad varchar(100) NOT NULL,
    matricula_prueba varchar(64) NOT NULL UNIQUE CHECK (matricula_prueba LIKE 'PRUEBA-%'),
    tipo_perfil varchar(32) NOT NULL CHECK (tipo_perfil = 'PRUEBA_OPERATIVA'),
    identidad_estado varchar(32) NOT NULL CHECK (identidad_estado = 'DECLARADA_NO_VERIFICADA'),
    matricula_estado varchar(32) NOT NULL CHECK (matricula_estado = 'FICTICIA_NO_VERIFICADA'),
    activo boolean NOT NULL DEFAULT false,
    creado_en timestamptz NOT NULL,
    vence_en timestamptz NOT NULL CHECK (vence_en > creado_en),
    consentimiento_contacto_en timestamptz NOT NULL,
    aviso_version varchar(32) NOT NULL
);
CREATE INDEX ix_op_sesion_campania ON operativa.sesion(campania_id);
CREATE INDEX ix_op_invitacion_campania ON operativa.invitacion(campania_id);

GRANT USAGE ON SCHEMA public, operativa TO operativa_runtime;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO operativa_runtime;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA operativa TO operativa_runtime;
COMMIT;
